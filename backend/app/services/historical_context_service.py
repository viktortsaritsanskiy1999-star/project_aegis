from datetime import datetime, timezone
from typing import Any, Callable, Dict, List, Optional
from pydantic import BaseModel, Field

from sqlalchemy.orm import Session

from app.models.medical_cycle import MedicalCycle
from app.repositories.cycle_repository import MedicalCycleRepository
from app.repositories.report_repository import ModelReportRepository
from app.schemas.privacy import PrivacyLevel

# Canonical report types
PRIMARY_OVERALL_CLIENT_REPORT_TYPE = "user_overall_report"
PRIMARY_CHIEF_INTERNAL_REPORT_TYPE = "chief_physician_internal"
WEEKLY_OVERALL_CLIENT_REPORT_TYPE = "weekly_user_overall_report"
WEEKLY_CHIEF_INTERNAL_REPORT_TYPE = "weekly_chief_physician_internal"
WEEKLY_DEPUTY_INTERNAL_REPORT_TYPE = "weekly_deputy_internal"
ATHENA_ACTIVE_STRATEGY_REPORT_TYPE = "athena_active_strategy"
PREPARATORY_ECG_REPORT_TYPE = "preparatory_vision_ecg"
LEGACY_ECG_REPORT_TYPE = "preparatory_ecg_intake"
LABORATORY_LEDGER_REPORT_TYPE = "laboratory_ledger"
REFERRAL_LIFECYCLE_STATE_REPORT_TYPE = "referral_lifecycle_state"
REFERRAL_DOCTOR_DOCUMENT_REPORT_TYPE = "referral_doctor_document"
ATHENA_CLINICAL_LOG_REPORT_TYPE = "athena_clinical_log"
ATHENA_DAILY_JOURNAL_REPORT_TYPE = "athena_daily_journal"

CLINICAL_GOVERNANCE_NOTICE = (
    "> **[CLINICAL NOTICE]**:\n"
    "> All AI conclusions, risk assessments, and recommendations summarized below are historical "
    "algorithmic observations and assistive hypotheses generated by Project Aegis AI consilium models. "
    "They are **NOT** confirmed medical diagnoses and must not be treated as final clinical conclusions "
    "without physician verification."
)


class HistoricalContextSummary(BaseModel):
    """
    Deterministic bounded historical context summary compiled across prior clinical cycles.
    Zero Gemini calls. Distinguishes algorithmic observations from confirmed clinical diagnoses.
    """
    patient_id: str
    assembled_at_utc: str
    prior_cycles_count: int
    prior_cycle_ids: List[str] = Field(default_factory=list)
    formatted_markdown: str
    character_count: int
    is_condensed: bool = False
    abnormal_labs_count: int = 0
    referrals_count: int = 0


class HistoricalContextService:
    """
    Service responsible for assembling a deterministic bounded longitudinal summary
    from all historical cycles of a patient prior to Neo Consilium (Stage 8B.1).
    Invariants:
    1. Zero Gemini calls: deterministic DB extraction and markdown generation.
    2. Prominent clinical governance notice differentiating AI hypotheses from confirmed diagnoses.
    3. Strictly bounded character limit (~8,000 characters) with deterministic condensation.
    4. Extracts Primary Consilia, latest Weekly Consilia, lab abnormal ledger entries, ECG conclusions,
       referral records with visit confirmation, and symptom trajectory.
    """

    def __init__(
        self,
        db: Session,
        now_provider: Optional[Callable[[], datetime]] = None,
    ):
        self.db = db
        self.now_provider = now_provider or (lambda: datetime.now(timezone.utc))
        self.cycle_repo = MedicalCycleRepository(db)
        self.report_repo = ModelReportRepository(db)

    def _now_utc(self) -> datetime:
        dt = self.now_provider()
        if dt.tzinfo is None:
            return dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(timezone.utc)

    def build_historical_context(
        self,
        patient_id: str,
        exclude_cycle_id: Optional[str] = None,
        max_characters: int = 8000,
    ) -> HistoricalContextSummary:
        """
        Gathers and deterministically formats bounded longitudinal context across all
        prior cycles for `patient_id`.
        """
        clean_patient = (patient_id or "").strip()
        now_dt = self._now_utc()
        now_iso = now_dt.isoformat()

        if not clean_patient:
            return HistoricalContextSummary(
                patient_id="",
                assembled_at_utc=now_iso,
                prior_cycles_count=0,
                prior_cycle_ids=[],
                formatted_markdown="# Historical Health Context Summary\n\nNo patient specified.\n",
                character_count=len("# Historical Health Context Summary\n\nNo patient specified.\n"),
                is_condensed=False,
            )

        # 1. Resolve all cycles for patient, excluding the currently pending or requested cycle
        all_cycles = self.cycle_repo.list_by_patient(clean_patient)
        prior_cycles = [
            c for c in all_cycles
            if c.cycle_id != exclude_cycle_id and c.status != "pending_reassessment"
        ]
        # Order prior cycles chronologically (oldest to newest)
        prior_cycles.sort(key=lambda c: c.started_at or datetime.min.replace(tzinfo=timezone.utc))

        prior_cycle_ids = [c.cycle_id for c in prior_cycles]

        if not prior_cycles:
            empty_md = (
                f"# Historical Health Context Summary\n"
                f"**Patient ID:** {clean_patient}\n"
                f"**Assembled at (UTC):** {now_iso}\n\n"
                f"{CLINICAL_GOVERNANCE_NOTICE}\n\n"
                f"No prior clinical observation cycles recorded for this patient.\n"
            )
            return HistoricalContextSummary(
                patient_id=clean_patient,
                assembled_at_utc=now_iso,
                prior_cycles_count=0,
                prior_cycle_ids=[],
                formatted_markdown=empty_md,
                character_count=len(empty_md),
                is_condensed=False,
            )

        # 2. Extract sections per cycle
        sections_primary: List[str] = []
        sections_weekly: List[str] = []
        abnormal_labs_lines: List[str] = []
        ecg_lines: List[str] = []
        referral_lines: List[str] = []
        symptom_set: set[str] = set()

        total_abnormal_labs = 0
        total_referrals = 0

        for cyc in prior_cycles:
            cid = cyc.cycle_id
            start_str = cyc.started_at.strftime("%Y-%m-%d") if cyc.started_at else "unknown"
            close_str = cyc.closed_at.strftime("%Y-%m-%d") if cyc.closed_at else "completed"

            # Primary Consilium
            p_client = self.report_repo.list_client_facing(cycle_id=cid, report_type=PRIMARY_OVERALL_CLIENT_REPORT_TYPE)
            p_internal = self.report_repo.list_server_only(cycle_id=cid, report_type=PRIMARY_CHIEF_INTERNAL_REPORT_TYPE)
            if p_client or p_internal:
                p_text = ""
                if p_client:
                    c = p_client[0].content or {}
                    p_text = f"- **Cycle `{cid}` ({start_str} to {close_str}):** {c.get('title', 'Primary Consilium')}: {c.get('summary', 'No summary available.')}"
                elif p_internal:
                    c = p_internal[0].content or {}
                    p_text = f"- **Cycle `{cid}` ({start_str} to {close_str}):** [Internal Pro Baseline]: {c.get('pro_training_summary', 'Baseline established.')}"
                sections_primary.append(p_text)

            # Latest Weekly Consilium
            w_client = self.report_repo.list_client_facing(cycle_id=cid, report_type=WEEKLY_OVERALL_CLIENT_REPORT_TYPE)
            w_internal = self.report_repo.list_server_only(cycle_id=cid, report_type=WEEKLY_CHIEF_INTERNAL_REPORT_TYPE)
            w_strategy = self.report_repo.list_server_only(cycle_id=cid, report_type=ATHENA_ACTIVE_STRATEGY_REPORT_TYPE)

            if w_client or w_internal:
                w_text = f"- **Cycle `{cid}` Latest Weekly:** "
                if w_client:
                    wc = w_client[0].content or {}
                    metrics = wc.get("metrics") or {}
                    sprint_num = metrics.get("sprint_number", 1)
                    w_text += f"Sprint {sprint_num} Summary: {wc.get('summary', 'Weekly review concluded.')}"
                elif w_internal:
                    wc = w_internal[0].content or {}
                    w_text += f"Chief Pro Strategy: {wc.get('updated_weekly_strategy', 'Maintained observation.')[:300]}"
                if w_strategy:
                    strat_ver = (w_strategy[0].content or {}).get("strategy_version", 1)
                    w_text += f" (Strategy Version: v{strat_ver})"
                sections_weekly.append(w_text)

            # Laboratory Ledger Abnormal Markers
            ledgers = self.report_repo.list_server_only(cycle_id=cid, report_type=LABORATORY_LEDGER_REPORT_TYPE)
            if ledgers:
                latest_ledger = ledgers[0]
                l_content = latest_ledger.content or {}
                active_markers = l_content.get("active_markers") or {}
                for m_key, m_val in active_markers.items():
                    if isinstance(m_val, dict):
                        is_crit = bool(m_val.get("is_critical_flag"))
                        val = m_val.get("value")
                        num_val = m_val.get("numeric_value")
                        unit = m_val.get("unit") or ""
                        sdate = m_val.get("sample_date") or start_str
                        disp_name = m_val.get("display_name") or m_key
                        ref_r = m_val.get("reference_range") or {}
                        ref_low = ref_r.get("low")
                        ref_high = ref_r.get("high")
                        ref_str = f"{ref_low}-{ref_high}" if (ref_low is not None and ref_high is not None) else (ref_r.get("text_range") or "n/a")

                        is_out_of_range = False
                        if num_val is not None and ref_low is not None and num_val < ref_low:
                            is_out_of_range = True
                        if num_val is not None and ref_high is not None and num_val > ref_high:
                            is_out_of_range = True

                        if is_crit or is_out_of_range:
                            flag_desc = (
                                "CRITICAL"
                                if is_crit
                                else (
                                    "ABOVE_REF"
                                    if (num_val is not None and ref_high is not None and num_val > ref_high)
                                    else "BELOW_REF"
                                )
                            )
                            abnormal_labs_lines.append(
                                f"| `{cid}` | {sdate} | {disp_name} | **{val} {unit}** | {ref_str} {unit} | {flag_desc} |"
                            )
                            total_abnormal_labs += 1

            # ECG Findings (supports canonical preparatory_vision_ecg and legacy preparatory_ecg_intake)
            ecg_reps = self.report_repo.list_server_only(cycle_id=cid, report_type=PREPARATORY_ECG_REPORT_TYPE)
            if not ecg_reps:
                ecg_reps = self.report_repo.list_server_only(cycle_id=cid, report_type=LEGACY_ECG_REPORT_TYPE)
            for ecg in ecg_reps:
                ec = ecg.content or {}
                ecg_date = ec.get("record_date") or (ecg.created_at.strftime("%Y-%m-%d") if ecg.created_at else start_str)
                rtype = ec.get("recording_type", "ECG")
                qual = ec.get("recording_quality", "moderate")
                hr = ec.get("heart_rate_bpm")
                hr_part = f", HR: {hr} bpm" if hr is not None else ""
                rhythm = (
                    ec.get("ecg_summary")
                    or ec.get("rhythm_type")
                    or ec.get("rhythm_classification")
                    or ec.get("conclusions")
                    or "Sinus rhythm evaluated"
                )
                urgent = ec.get("potential_urgent_warning")
                urg_part = f" [WARNING: {urgent}]" if urgent else ""
                ecg_lines.append(f"- **Cycle `{cid}` ({ecg_date}):** {rtype} (Quality: {qual}{hr_part}) — {rhythm}{urg_part}")

            # Referral Records & Visit Confirmation (deduplicated by referral_id, retaining latest lifecycle state)
            ref_states = self.report_repo.list_server_only(cycle_id=cid, report_type=REFERRAL_LIFECYCLE_STATE_REPORT_TYPE)
            latest_ref_states: Dict[str, Dict[str, Any]] = {}
            for rs in ref_states:
                rc = rs.content or {}
                ref_id = str(rc.get("referral_id") or rs.report_id or "REF-OBSERVATION")
                if ref_id not in latest_ref_states:
                    latest_ref_states[ref_id] = rc

            for ref_id, rc in latest_ref_states.items():
                ref_stat = rc.get("status", "none")
                specs = ", ".join(rc.get("target_specialties") or []) or "General Practitioner"
                urg = rc.get("urgency", "routine")
                reason = rc.get("clinical_reason_for_referral") or "Outpatient clinical verification"
                visit_conf = (
                    "CONFIRMED (Patient self-reported in-person doctor visit)"
                    if ref_stat == "visit_confirmed"
                    else "NOT CONFIRMED (No verified visit reported)"
                )
                referral_lines.append(
                    f"- **Referral `{ref_id}` (Cycle `{cid}`, Urgency: {urg.upper()}):** Specialty: {specs}. Reason: {reason}. Status: **{visit_conf}**."
                )
                total_referrals += 1

            # Symptoms & Daily Journals
            journals = self.report_repo.list_server_only(cycle_id=cid, report_type=ATHENA_DAILY_JOURNAL_REPORT_TYPE)
            for j in journals:
                jc = j.content or {}
                layer1 = jc.get("layer1_evidence") or {}
                symptoms = layer1.get("symptoms_reported") or []
                for s in symptoms:
                    if isinstance(s, str) and s.strip():
                        symptom_set.add(s.strip())

            clogs = self.report_repo.list_server_only(cycle_id=cid, report_type=ATHENA_CLINICAL_LOG_REPORT_TYPE)
            for cl in clogs:
                cc = cl.content or {}
                stmt = cc.get("statement_text")
                if stmt and isinstance(stmt, str) and cc.get("classification") in ("symptom", "complaint"):
                    symptom_set.add(stmt.strip())

        # 3. Assemble Markdown sections
        cycles_header = f"**Prior Cycles Count:** {len(prior_cycles)} (`{', '.join(prior_cycle_ids)}`)\n"

        p_sec = "## 1. Prior Cycles Overview & Primary Consilia\n"
        if sections_primary:
            p_sec += "\n".join(sections_primary) + "\n\n"
        else:
            p_sec += "_No previous primary consilia found._\n\n"

        w_sec = "## 2. Longitudinal Weekly Sprint Conclusions\n"
        if sections_weekly:
            w_sec += "\n".join(sections_weekly) + "\n\n"
        else:
            w_sec += "_No previous weekly consilia found._\n\n"

        l_sec = "## 3. Laboratory Ledger (Abnormal & Significant Markers)\n"
        if abnormal_labs_lines:
            l_sec += "| Cycle | Sample Date | Marker | Observed Value | Reference Interval | Flag |\n"
            l_sec += "| :--- | :--- | :--- | :--- | :--- | :--- |\n"
            l_sec += "\n".join(abnormal_labs_lines) + "\n\n"
        else:
            l_sec += "_All previously recorded laboratory parameters were within reference intervals._\n\n"

        e_sec = "## 4. Electrocardiogram (ECG) Historical Findings\n"
        if ecg_lines:
            e_sec += "\n".join(ecg_lines) + "\n\n"
        else:
            e_sec += "_No historical ECG recordings found._\n\n"

        r_sec = "## 5. Referral History & Visit Confirmation Status\n"
        if referral_lines:
            r_sec += "\n".join(referral_lines) + "\n\n"
        else:
            r_sec += "_No physician referrals were issued in prior cycles._\n\n"

        s_sec = "## 6. Longitudinal Symptom Trajectory\n"
        if symptom_set:
            s_sec += "Reported historical symptoms and focus areas:\n"
            for sym in sorted(symptom_set):
                s_sec += f"- {sym}\n"
            s_sec += "\n"
        else:
            s_sec += "_No persistent subjective symptoms recorded._\n\n"

        full_md = (
            f"# Historical Health Context Summary (Prior Cycles)\n"
            f"**Patient ID:** {clean_patient}\n"
            f"**Assembled at (UTC):** {now_iso}\n"
            f"{cycles_header}\n"
            f"{CLINICAL_GOVERNANCE_NOTICE}\n\n"
            f"{p_sec}"
            f"{w_sec}"
            f"{l_sec}"
            f"{e_sec}"
            f"{r_sec}"
            f"{s_sec}"
        )

        is_condensed = False
        # 4. Strict bounding to max_characters (~8,000 chars)
        if len(full_md) > max_characters:
            is_condensed = True
            # Step A: Condense narrative sections (p_sec and w_sec)
            p_truncated = [line[:150] + " [...]" if len(line) > 150 else line for line in sections_primary]
            w_truncated = [line[:150] + " [...]" if len(line) > 150 else line for line in sections_weekly]
            p_sec = "## 1. Prior Cycles Overview & Primary Consilia (Condensed)\n" + "\n".join(p_truncated) + "\n\n"
            w_sec = "## 2. Longitudinal Weekly Sprint Conclusions (Condensed)\n" + "\n".join(w_truncated) + "\n\n"

            # Step B: Condense symptoms if lengthy
            if len(symptom_set) > 8:
                sym_list = sorted(list(symptom_set))[:8]
                s_sec = "## 6. Cumulative Reported Symptoms & Complaints (Condensed)\n" + "\n".join(
                    [f"- {s}" for s in sym_list]
                ) + f"\n- *... and {len(symptom_set) - 8} additional reported symptoms condensed for brevity.*\n\n"

            full_md = (
                f"# Historical Health Context Summary (Prior Cycles - Condensed)\n"
                f"**Patient ID:** {clean_patient}\n"
                f"**Assembled at (UTC):** {now_iso}\n"
                f"{cycles_header}\n"
                f"{CLINICAL_GOVERNANCE_NOTICE}\n\n"
                f"{p_sec}"
                f"{w_sec}"
                f"{l_sec}"
                f"{e_sec}"
                f"{r_sec}"
                f"{s_sec}"
            )

            # Step C: If still over limit, heavily condense narratives and excess lab rows while strictly preserving notices, ECG, and referrals
            if len(full_md) > max_characters:
                p_truncated = [line[:75] + " [...]" if len(line) > 75 else line for line in sections_primary]
                w_truncated = [line[:75] + " [...]" if len(line) > 75 else line for line in sections_weekly]
                p_sec = "## 1. Prior Cycles Overview & Primary Consilia (Condensed)\n" + "\n".join(p_truncated) + "\n\n"
                w_sec = "## 2. Longitudinal Weekly Sprint Conclusions (Condensed)\n" + "\n".join(w_truncated) + "\n\n"

                if len(abnormal_labs_lines) > 10:
                    condensed_lab_lines = abnormal_labs_lines[:10] + [
                        f"| ... | ... | *[{len(abnormal_labs_lines) - 10} additional abnormal lab markers condensed]* | ... | ... | ... |"
                    ]
                    l_sec = (
                        "## 3. Laboratory Ledger (Cumulative Abnormal Markers - Condensed)\n"
                        "| Cycle | Sample Date | Marker | Value | Reference Range | Flag |\n"
                        "|---|---|---|---|---|---|\n"
                        + "\n".join(condensed_lab_lines)
                        + "\n\n"
                    )

                full_md = (
                    f"# Historical Health Context Summary (Prior Cycles - Condensed)\n"
                    f"**Patient ID:** {clean_patient}\n"
                    f"**Assembled at (UTC):** {now_iso}\n"
                    f"{cycles_header}\n"
                    f"{CLINICAL_GOVERNANCE_NOTICE}\n\n"
                    f"{p_sec}"
                    f"{w_sec}"
                    f"{l_sec}"
                    f"{e_sec}"
                    f"{r_sec}"
                    f"{s_sec}"
                )

                if len(full_md) > max_characters:
                    full_md = full_md[: max_characters - 80] + "\n\n[... Historical summary safely bounded to character limit ...]\n"

        return HistoricalContextSummary(
            patient_id=clean_patient,
            assembled_at_utc=now_iso,
            prior_cycles_count=len(prior_cycles),
            prior_cycle_ids=prior_cycle_ids,
            formatted_markdown=full_md,
            character_count=len(full_md),
            is_condensed=is_condensed,
            abnormal_labs_count=total_abnormal_labs,
            referrals_count=total_referrals,
        )
